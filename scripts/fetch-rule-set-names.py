"""List the rule-sets SagerNet publishes (sing-geosite and sing-geoip, `rule-set` branch) and write
them to src/rule-set-names.ts, which the rule editor searches and checks names against.

Usage: python3 scripts/fetch-rule-set-names.py
Set GITHUB_TOKEN to avoid the unauthenticated API rate limit.
"""

import datetime
import json
import os
import urllib.request

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "rule-set-names.ts")


def names(repo: str, prefix: str) -> list[str]:
    req = urllib.request.Request(f"https://api.github.com/repos/SagerNet/{repo}/git/trees/rule-set")
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req, timeout=60) as r:
        tree = json.load(r)
    if tree.get("truncated"):
        raise SystemExit(f"{repo}: tree listing truncated")
    files = [x["path"] for x in tree["tree"] if x["path"].startswith(prefix) and x["path"].endswith(".srs")]
    return sorted(f[len(prefix) : -len(".srs")] for f in files)


geosite = names("sing-geosite", "geosite-")
geoip = names("sing-geoip", "geoip-")
today = datetime.date.today().isoformat()
with open(OUT, "w") as f:
    f.write("// Generated by scripts/fetch-rule-set-names.py; do not edit.\n")
    f.write("// The rule-sets on the `rule-set` branch of SagerNet/sing-geosite and SagerNet/sing-geoip, without prefix and extension.\n\n")
    f.write(f'export const RULE_SET_NAMES_DATE = "{today}";\n\n')
    f.write(f"export const GEOSITE_NAMES: string[] = {json.dumps(' '.join(geosite))}.split(\" \");\n\n")
    f.write(f"export const GEOIP_NAMES: string[] = {json.dumps(' '.join(geoip))}.split(\" \");\n")
print(f"{len(geosite)} geosite, {len(geoip)} geoip → {os.path.normpath(OUT)}")
